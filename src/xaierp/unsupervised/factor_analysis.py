"""Factor Analysis by EM, with varimax rotation (Unit 3).

The generative model
--------------------
    z ~ N(0, I)                  L continuous latent factors
    x = W z + mu + eps           eps ~ N(0, Psi), Psi DIAGONAL

Marginalising the latent factor gives a Gaussian with a *structured*
covariance:

    cov(x) = W W^T + Psi         low rank  +  diagonal

That structure is the whole idea. A full covariance over d observed variables
needs d(d+1)/2 parameters; FA needs Ld for W plus d for Psi. The claim being
made is that all the correlation between the observed profile columns is
generated by L shared factors, and whatever is left over is independent noise
specific to each column.

FA vs PCA -- a real distinction, not a naming quibble
-----------------------------------------------------
PCA explains TOTAL variance and has no noise model: every component is a
direction in the data, including directions that are pure measurement noise.
FA explains only the SHARED variance, pushing the column-specific part into
the diagonal Psi. So FA is scale-aware in a way PCA is not: a column that is
mostly its own noise gets a large Psi entry and is largely ignored, where PCA
would happily spend a component on it.

Identifiability
---------------
For any orthogonal R, W' = WR gives W'W'^T = WRR^TW^T = WW^T -- an identical
covariance and therefore an identical likelihood. **The loadings are not
unique.** `rotational_ambiguity_check` demonstrates this numerically, and it
is the licence under which `varimax` operates: rotating to a more
interpretable solution costs nothing in fit because every rotation fits
exactly as well. Non-identifiability affects interpretation, not prediction.
"""

from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np


@dataclass
class FactorAnalysisEM:
    """Factor analysis fitted by Expectation-Maximization."""

    n_factors: int
    # FA's EM converges slowly: the loadings and the noise variances compete
    # for the same variance, so the tail takes thousands of sweeps to add
    # another decimal place. Measured on the 200-SKU profile matrix, tol=1e-8
    # converges in ~2,400 iterations at a log-likelihood within 0.06 of what
    # tol=1e-9 reaches in ~8,200 -- so this is the knee, not an arbitrary cap.
    max_iter: int = 20000
    tol: float = 1e-8
    noise_floor: float = 1e-6
    random_state: int = 42

    # Fitted state.
    mean_: np.ndarray | None = None
    loadings_: np.ndarray | None = None       # W, shape (n_features, n_factors)
    noise_variance_: np.ndarray | None = None  # diag(Psi), shape (n_features,)
    loglik_history_: list[float] = field(default_factory=list)
    n_iter_: int = 0
    converged_: bool = False

    # ------------------------------------------------------------ helpers

    def _model_covariance(self) -> np.ndarray:
        """C = W W^T + Psi."""
        return self.loadings_ @ self.loadings_.T + np.diag(self.noise_variance_)

    def log_likelihood(self, X: np.ndarray) -> float:
        """Sum of log N(x | mu, WW^T + Psi).

        Evaluated through the Cholesky factor of C for the same reason as in
        gmm.py: one factorisation yields both the quadratic form and the
        log-determinant, and it raises rather than returning nonsense if C
        stops being positive definite.
        """
        X = np.asarray(X, dtype=float)
        n, d = X.shape
        C = self._model_covariance()
        L = np.linalg.cholesky(C)
        diff = (X - self.mean_).T
        z = np.linalg.solve(L, diff)
        maha = np.sum(z**2)
        log_det = 2.0 * np.sum(np.log(np.diag(L)))
        return float(-0.5 * (n * d * np.log(2 * np.pi) + n * log_det + maha))

    # ---------------------------------------------------------------- fit

    def fit(self, X: np.ndarray) -> "FactorAnalysisEM":
        X = np.asarray(X, dtype=float)
        n, d = X.shape
        L = self.n_factors
        if L >= d:
            raise ValueError(
                f"n_factors={L} must be < n_features={d}; with L >= d the "
                "low-rank structure is vacuous."
            )

        rng = np.random.default_rng(self.random_state)
        self.mean_ = X.mean(axis=0)
        Xc = X - self.mean_

        # Initialise W small and random, Psi at the observed variances. A
        # zero W is a stationary point of EM, so it must not be the start.
        self.loadings_ = rng.normal(scale=0.1, size=(d, L))
        self.noise_variance_ = np.maximum(Xc.var(axis=0, ddof=0), self.noise_floor)

        S = (Xc.T @ Xc) / n          # sample covariance, biased -- matches EM
        self.loglik_history_ = []
        prev = -np.inf

        for it in range(1, self.max_iter + 1):
            W, Psi = self.loadings_, self.noise_variance_
            Psi_inv = 1.0 / Psi

            # ---- E-step: posterior over the latent factors.
            #   Sigma_z = (I + W^T Psi^-1 W)^-1
            #   E[z|x]  = Sigma_z W^T Psi^-1 (x - mu)
            #   E[zz^T|x] = Sigma_z + E[z|x] E[z|x]^T
            # Inverting the L x L matrix, never the d x d one -- this is the
            # Woodbury trick that makes FA cheap when L << d.
            G = W.T * Psi_inv                           # (L, d)
            Sigma_z = np.linalg.inv(np.eye(L) + G @ W)  # (L, L)
            beta = Sigma_z @ G                          # (L, d)

            Ez = Xc @ beta.T                            # (n, L)
            Ezz = n * Sigma_z + Ez.T @ Ez               # (L, L), summed over n

            # ---- M-step: closed-form maximisation.
            W_new = (Xc.T @ Ez) @ np.linalg.inv(Ezz)
            # Psi = diag( S - W_new * (1/n) * E[z]^T Xc )
            Psi_new = np.diag(S - W_new @ (Ez.T @ Xc) / n)
            Psi_new = np.maximum(Psi_new, self.noise_floor)

            self.loadings_ = W_new
            self.noise_variance_ = Psi_new

            ll = self.log_likelihood(X)
            self.loglik_history_.append(ll)
            self.n_iter_ = it

            if np.isfinite(prev) and abs(ll - prev) <= self.tol * abs(prev):
                self.converged_ = True
                break
            prev = ll

        return self

    # ---------------------------------------------------------- inference

    def transform(self, X: np.ndarray) -> np.ndarray:
        """Posterior mean latent scores E[z | x] -- "where does this SKU sit?"."""
        X = np.asarray(X, dtype=float)
        W, Psi = self.loadings_, self.noise_variance_
        G = W.T / Psi
        Sigma_z = np.linalg.inv(np.eye(self.n_factors) + G @ W)
        return (X - self.mean_) @ (Sigma_z @ G).T

    def fit_transform(self, X: np.ndarray) -> np.ndarray:
        return self.fit(X).transform(X)

    def communalities(self) -> np.ndarray:
        """Share of each observed variable's variance explained by the factors.

        h_j^2 = sum_l W_jl^2, divided by the total modelled variance
        (h_j^2 + Psi_j). A low communality means that column is mostly its own
        noise and the shared factors say little about it.
        """
        h2 = np.sum(self.loadings_**2, axis=1)
        return h2 / (h2 + self.noise_variance_)

    def n_parameters(self) -> int:
        """Free parameters: d (mean) + Ld (loadings) + d (Psi) - L(L-1)/2.

        The subtraction is the rotational ambiguity: an L x L orthogonal
        rotation has L(L-1)/2 free angles that change W without changing the
        likelihood at all, so those directions are not real parameters.
        """
        d, L = self.loadings_.shape
        return int(d + L * d + d - L * (L - 1) / 2)


# ------------------------------------------------------------- rotation


def varimax(W: np.ndarray, gamma: float = 1.0, max_iter: int = 500,
            tol: float = 1e-6) -> tuple[np.ndarray, np.ndarray]:
    """Varimax rotation: make the loadings interpretable without changing fit.

    Maximises the variance of the SQUARED loadings within each factor. The
    effect is to push every loading towards either 0 or +/-1, so each factor
    ends up loading strongly on a few variables instead of weakly on all of
    them -- "simple structure". Because the rotation is orthogonal it leaves
    W W^T, and therefore the likelihood, untouched.

    Returns ``(W_rotated, R)`` with ``W_rotated = W @ R``.
    """
    W = np.asarray(W, dtype=float)
    d, L = W.shape
    if L < 2:
        return W.copy(), np.eye(L)

    R = np.eye(L)
    prev = 0.0
    for _ in range(max_iter):
        Lam = W @ R
        # Gradient of the varimax criterion, solved by SVD at each step.
        B = Lam**3 - (gamma / d) * Lam @ np.diag(np.sum(Lam**2, axis=0))
        U, s, Vt = np.linalg.svd(W.T @ B)
        R = U @ Vt
        crit = float(np.sum(s))
        if prev != 0.0 and abs(crit - prev) <= tol * abs(prev):
            break
        prev = crit
    return W @ R, R


def rotational_ambiguity_check(
    model: "FactorAnalysisEM", X: np.ndarray, seed: int = 0
) -> dict[str, float]:
    """Show numerically that W is identified only up to an orthogonal rotation.

    Rotates the fitted loadings by a random orthogonal R and re-evaluates the
    log-likelihood. `loglik_difference` comes back at machine precision --
    the rotated model is a *different* W that fits *exactly* as well. This is
    the result that licenses varimax, and the reason factor loadings must
    never be reported as if they were unique.
    """
    rng = np.random.default_rng(seed)
    L = model.n_factors

    # A Haar-random orthogonal matrix via the QR of a Gaussian matrix.
    Q, _ = np.linalg.qr(rng.normal(size=(L, L)))

    ll_before = model.log_likelihood(X)
    W_original = model.loadings_.copy()

    model.loadings_ = W_original @ Q
    ll_after = model.log_likelihood(X)
    cov_after = model._model_covariance()

    model.loadings_ = W_original
    cov_before = model._model_covariance()

    return {
        "loglik_original": ll_before,
        "loglik_rotated": ll_after,
        "loglik_difference": abs(ll_after - ll_before),
        "max_covariance_difference": float(np.max(np.abs(cov_after - cov_before))),
        "max_loading_difference": float(np.max(np.abs(W_original @ Q - W_original))),
        "n_free_rotations": int(L * (L - 1) / 2),
    }
