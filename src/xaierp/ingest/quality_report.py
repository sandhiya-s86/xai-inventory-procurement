"""Data-quality reporting.

Produces reports/data_quality_report.json: the evidence behind every claim
made about the dataset in the report, the EDA notebook and the viva answers.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from ..utils.config import ensure_dir, load_config, resolve


def _missing_table(df: pd.DataFrame) -> dict[str, dict[str, float]]:
    n = len(df)
    return {
        col: {
            "n_missing": int(df[col].isna().sum()),
            "pct_missing": round(100.0 * df[col].isna().mean(), 4),
            "n_unique": int(df[col].nunique(dropna=True)),
            "dtype": str(df[col].dtype),
        }
        for col in df.columns
    }


def _numeric_summary(df: pd.DataFrame, cols: list[str]) -> dict[str, dict[str, float]]:
    out: dict[str, dict[str, float]] = {}
    for col in cols:
        if col not in df.columns:
            continue
        s = pd.to_numeric(df[col], errors="coerce").dropna()
        if s.empty:
            continue
        out[col] = {
            "count": int(s.size),
            "mean": float(s.mean()),
            "std": float(s.std(ddof=1)),
            "variance": float(s.var(ddof=1)),
            "min": float(s.min()),
            "q25": float(s.quantile(0.25)),
            "median": float(s.median()),
            "q75": float(s.quantile(0.75)),
            "q90": float(s.quantile(0.90)),
            "q95": float(s.quantile(0.95)),
            "q99": float(s.quantile(0.99)),
            "max": float(s.max()),
            "skew": float(s.skew()),
            "n_negative": int((s < 0).sum()),
            "n_zero": int((s == 0).sum()),
        }
    return out


def build_quality_report(
    raw: pd.DataFrame,
    clean: pd.DataFrame,
    cleaning_log: Any,
    panel: pd.DataFrame,
    panel_meta: dict[str, Any],
) -> dict[str, Any]:
    """Assemble the full quality report as a plain dict."""
    raw_dates = pd.to_datetime(raw["invoice_date"], errors="coerce")

    # Which weekdays does this business actually trade on? A real finding.
    traded = clean.groupby(clean["date"].dt.dayofweek)["invoice"].nunique()
    weekday_names = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]
    weekday_trading = {
        weekday_names[i]: int(traded.get(i, 0)) for i in range(7)
    }

    report: dict[str, Any] = {
        "dataset": {
            "name": "UCI Online Retail II",
            "source_url": "https://archive.ics.uci.edu/dataset/502/online+retail+ii",
            "licence": "CC BY 4.0",
            "nature": "Real transactional sales data (invoice lines).",
            "simulated_components": (
                "No inventory, supplier, lead-time or cost data exists in this "
                "dataset. Those are generated by sim/ and are clearly labelled "
                "SIMULATED throughout the project."
            ),
        },
        "raw": {
            "n_rows": int(len(raw)),
            "n_cols": int(raw.shape[1]),
            "date_min": str(raw_dates.min()),
            "date_max": str(raw_dates.max()),
            "n_invoices": int(raw["invoice"].nunique()),
            "n_stock_codes": int(raw["stock_code"].nunique()),
            "n_customers": int(raw["customer_id"].nunique(dropna=True)),
            "n_countries": int(raw["country"].nunique(dropna=True)),
            "missing_by_column": _missing_table(raw),
            "numeric_summary": _numeric_summary(raw, ["quantity", "price"]),
            "n_exact_duplicate_rows": int(raw.duplicated().sum()),
        },
        "cleaning": cleaning_log.to_dict()
        if hasattr(cleaning_log, "to_dict")
        else cleaning_log,
        "clean": {
            "n_rows": int(len(clean)),
            "n_invoices": int(clean["invoice"].nunique()),
            "n_stock_codes": int(clean["stock_code"].nunique()),
            "n_customers": int(clean["customer_id"].nunique(dropna=True)),
            "n_countries": int(clean["country"].nunique(dropna=True)),
            "date_min": str(clean["date"].min().date()),
            "date_max": str(clean["date"].max().date()),
            "total_units": float(clean["quantity"].sum()),
            "total_revenue": float(clean["revenue"].sum()),
            "numeric_summary": _numeric_summary(
                clean, ["quantity", "price", "revenue"]
            ),
            "invoices_by_weekday": weekday_trading,
            "top_countries_by_revenue": clean.groupby("country")["revenue"]
            .sum()
            .sort_values(ascending=False)
            .head(10)
            .round(2)
            .to_dict(),
        },
        "panel": {
            **panel_meta,
            "demand_summary": _numeric_summary(panel, ["demand"])["demand"],
            "n_duplicate_sku_date_rows": int(
                panel.duplicated(subset=["stock_code", "date"]).sum()
            ),
            "n_missing_demand": int(panel["demand"].isna().sum()),
            "n_negative_demand": int((panel["demand"] < 0).sum()),
        },
    }
    return report


def write_quality_report(report: dict[str, Any]) -> Path:
    """Write the report to reports/data_quality_report.json."""
    cfg = load_config()
    out = resolve(cfg["paths"]["reports"]) / "data_quality_report.json"
    ensure_dir(out)

    def default(o):
        if isinstance(o, (np.integer,)):
            return int(o)
        if isinstance(o, (np.floating,)):
            return float(o)
        if isinstance(o, (pd.Timestamp,)):
            return str(o)
        return str(o)

    with out.open("w", encoding="utf-8") as fh:
        json.dump(report, fh, indent=2, default=default)
    return out
